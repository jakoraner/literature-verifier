"""Summary report (markdown, HTML, JSON) of the ledger and the metadata audit."""

from __future__ import annotations

import html
import json
from collections import Counter

from . import VERDICTS
from .rules import RULES, Violation


def summarise(rows: list[dict[str, str]], meta_rows: list[dict[str, str]],
              violations: list[Violation]) -> dict:
    live = [r for r in rows if r["status"] == "live"]
    verdicts = Counter(r["verdict"] for r in live)
    return {
        "citations_live": len(live),
        "citations_removed": sum(r["status"] == "removed" for r in rows),
        "sources": len({r["key"] for r in live}),
        "verdicts": {v: verdicts.get(v, 0) for v in VERDICTS},
        "decided": sum(bool(r["decision"]) for r in live),
        "without_pdf": sorted({r["key"] for r in live if not r["pdf"]}),
        "metadata": dict(Counter(r["status"] for r in meta_rows)),
        "violations_by_rule": dict(Counter(v.rule for v in violations)),
        "open_items": [{"rule": v.rule, "where": v.where, "detail": v.detail}
                       for v in violations],
    }


def markdown(s: dict) -> str:
    L = ["# Citation verification report", ""]
    L.append(f"- Live citations: **{s['citations_live']}** to **{s['sources']}** sources "
             f"({s['citations_removed']} removed rows kept)")
    L.append(f"- Human decisions recorded: {s['decided']}")
    L.append(f"- Sources without a PDF: {len(s['without_pdf'])}"
             + (" (" + ", ".join(f"`{k}`" for k in s["without_pdf"]) + ")"
                if s["without_pdf"] else ""))
    L += ["", "| Verdict | Citations |", "|---|---|"]
    L += [f"| {v} | {n} |" for v, n in s["verdicts"].items()]
    L += ["", "| Metadata field status | Count |", "|---|---|"]
    L += [f"| {k} | {n} |" for k, n in sorted(s["metadata"].items())]
    L += ["", f"## Open items: {len(s['open_items'])}", ""]
    if not s["open_items"]:
        L.append("None. Every citation passes rules R1 to R7.")
    else:
        L += ["| Rule | Where | Detail |", "|---|---|---|"]
        for o in s["open_items"]:
            d = o["detail"].replace("|", "\\|")
            L.append(f"| {o['rule']} {RULES[o['rule']]} | {o['where']} | {d} |")
    return "\n".join(L) + "\n"


def to_html(s: dict) -> str:
    e = html.escape
    rows = "".join(
        f"<tr><td>{e(o['rule'])}</td><td>{e(o['where'])}</td><td>{e(o['detail'])}</td></tr>"
        for o in s["open_items"])
    verdicts = "".join(f"<tr><td>{e(v)}</td><td>{n}</td></tr>" for v, n in s["verdicts"].items())
    meta = "".join(f"<tr><td>{e(k)}</td><td>{n}</td></tr>"
                   for k, n in sorted(s["metadata"].items()))
    status = ("All citations pass." if not s["open_items"]
              else f"{len(s['open_items'])} open items.")
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Citation verification report</title>
<style>
:root {{ --fg:#1b1b1b; --bg:#fff; --mute:#666; --line:#ddd; --bad:#a3261b; --ok:#1f6f3a; }}
@media (prefers-color-scheme: dark) {{
  :root {{ --fg:#e8e8e8; --bg:#161616; --mute:#9a9a9a; --line:#333; --bad:#ff8a7a;
          --ok:#7fd49a; }} }}
body {{ font: 15px/1.5 system-ui, sans-serif; color: var(--fg); background: var(--bg);
       max-width: 70rem; margin: 2rem auto; padding: 0 16px; }}
table {{ border-collapse: collapse; margin: 1rem 0; width: 100%; }}
td, th {{ border-bottom: 1px solid var(--line); padding: .3rem .5rem; text-align: left;
         vertical-align: top; }}
.status {{ font-weight: 600; color: {"var(--ok)" if not s["open_items"] else "var(--bad)"}; }}
.mute {{ color: var(--mute); }}
</style></head><body>
<h1>Citation verification report</h1>
<p class="status">{e(status)}</p>
<p>{s['citations_live']} live citations to {s['sources']} sources;
{s['decided']} human decisions; {len(s['without_pdf'])} sources without a PDF.</p>
<h2>Verdicts</h2><table><tr><th>Verdict</th><th>Citations</th></tr>{verdicts}</table>
<h2>Metadata audit</h2><table><tr><th>Status</th><th>Fields</th></tr>{meta}</table>
<h2>Open items</h2>
<table><tr><th>Rule</th><th>Where</th><th>Detail</th></tr>{rows}</table>
<p class="mute">Generated by literature-verifier.</p>
</body></html>
"""


def to_json(s: dict) -> str:
    return json.dumps(s, indent=1, ensure_ascii=False)
